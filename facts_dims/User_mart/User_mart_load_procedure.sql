CREATE OR REPLACE PROCEDURE ECOMMERCE.CLEAN.SP_LOAD_FACT_LOGIN()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO ECOMMERCE.USER_MART.FACT_LOGIN AS TARGET
    USING (
        SELECT
            DU.USER_KEY,
            DD.DEVICE_KEY,
            DI.IP_KEY,
            DDATE.DATE_KEY,
            DTIME.TIME_KEY,
            DLS.STATUS_KEY,
            1 AS LOGIN_COUNT
        FROM ECOMMERCE.CLEAN.CLEAN_USER_STREAM AS SRC
        INNER JOIN ECOMMERCE.USER_MART.DIM_USER AS DU
            ON SRC.USER_ID = DU.USER_ID
        INNER JOIN ECOMMERCE.USER_MART.DIM_DEVICE AS DD
            ON SRC.DEVICE_NAME = DD.DEVICE_NAME
           AND SRC.BROWSER = DD.BROWSER
        INNER JOIN ECOMMERCE.USER_MART.DIM_IP AS DI
            ON SRC.IP_ADDRESS = DI.IP_ADDRESS
        INNER JOIN ECOMMERCE.USER_MART.DIM_DATE AS DDATE
            ON SRC.FULL_DATE = DDATE.FULL_DATE
        INNER JOIN ECOMMERCE.USER_MART.DIM_TIME AS DTIME
            ON SRC.HOUR = DTIME.HOUR
           AND SRC.MINUTE = DTIME.MINUTE
           AND SRC.SECOND = DTIME.SECOND
        INNER JOIN ECOMMERCE.USER_MART.DIM_LOGIN_STATUS AS DLS
            ON SRC.LOGIN_STATUS = DLS.LOGIN_STATUS
    ) AS SRC
        ON TARGET.USER_KEY   = SRC.USER_KEY
       AND TARGET.DEVICE_KEY = SRC.DEVICE_KEY
       AND TARGET.IP_KEY     = SRC.IP_KEY
       AND TARGET.DATE_KEY   = SRC.DATE_KEY
       AND TARGET.TIME_KEY   = SRC.TIME_KEY
       AND TARGET.STATUS_KEY = SRC.STATUS_KEY

    WHEN NOT MATCHED THEN
        INSERT (USER_KEY, DEVICE_KEY, IP_KEY, DATE_KEY, TIME_KEY, STATUS_KEY, LOGIN_COUNT)
        VALUES (SRC.USER_KEY, SRC.DEVICE_KEY, SRC.IP_KEY, SRC.DATE_KEY, SRC.TIME_KEY, SRC.STATUS_KEY, SRC.LOGIN_COUNT);

    RETURN 'FACT_LOGIN LOAD SUCCESSFUL';
END;
$$;


