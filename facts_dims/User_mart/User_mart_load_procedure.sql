            SRC.MONTH,
            SRC.QUARTER,
            SRC.YEAR,
            SRC.DAY_NAME
        );

    RETURN 'DIM_DATE LOAD SUCCESSFUL';
END;
$$;


CREATE OR REPLACE PROCEDURE ECOMMERCE.CLEAN.SP_LOAD_DIM_TIME()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO ECOMMERCE.USER_MART.DIM_TIME AS TARGET
    USING (
        SELECT DISTINCT
            HOUR,
            MINUTE,
            SECOND
        FROM ECOMMERCE.CLEAN.CLEAN_USER_STREAM
        WHERE HOUR IS NOT NULL
          AND MINUTE IS NOT NULL
          AND SECOND IS NOT NULL
    ) AS SRC
        ON TARGET.HOUR = SRC.HOUR
       AND TARGET.MINUTE = SRC.MINUTE
       AND TARGET.SECOND = SRC.SECOND

    WHEN NOT MATCHED THEN
        INSERT (TIME_KEY, HOUR, MINUTE, SECOND)
        VALUES (
            SRC.HOUR * 10000 + SRC.MINUTE * 100 + SRC.SECOND,
            SRC.HOUR,
            SRC.MINUTE,
            SRC.SECOND
        );

    RETURN 'DIM_TIME LOAD SUCCESSFUL';
END;
$$;


