CREATE OR REPLACE PROCEDURE ECOMMERCE.CLEAN.SP_LOAD_DIM_USER()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
    MERGE INTO ECOMMERCE.USER_MART.DIM_USER AS USR
    USING ECOMMERCE.CLEAN.CLEAN_USER_STREAM AS SRC
        ON USR.USER_ID = SRC.USER_ID

    WHEN MATCHED THEN
        UPDATE SET
            USR.FIRST_NAME    = SRC.FIRST_NAME,
            USR.LAST_NAME     = SRC.LAST_NAME,
            USR.MIDDLE_NAME   = SRC.MIDDLE_NAME,
            USR.EMAIL         = SRC.EMAIL,
            USR.PASSWORD_HASH = SRC.PASSWORD_HASH,
            USR.STATUS        = SRC.STATUS,
            USR.CREATED_AT    = SRC.CREATED_AT,
            USR.UPDATED_AT    = SRC.UPDATED_AT

    WHEN NOT MATCHED THEN
        INSERT (USER_ID, FIRST_NAME, LAST_NAME, MIDDLE_NAME, EMAIL, PASSWORD_HASH, STATUS, CREATED_AT, UPDATED_AT)
        VALUES (SRC.USER_ID, SRC.FIRST_NAME, SRC.LAST_NAME, SRC.MIDDLE_NAME, SRC.EMAIL, SRC.PASSWORD_HASH, SRC.STATUS, SRC.CREATED_AT, SRC.UPDATED_AT);

    RETURN 'DIM_USER LOAD SUCCESSFUL';
END;
$$;


CREATE OR REPLACE PROCEDURE ECOMMERCE.CLEAN.SP_LOAD_DIM_ADDRESS()
RETURNS STRING
LANGUAGE SQL
AS 
$$
BEGIN
    MERGE INTO ECOMMERCE.USER_MART.DIM_ADDRESS AS ADDR
    USING (
        SELECT
            STR.ADDRESS_ID,
            DU.USER_KEY,
            STR.COUNTRY,
            STR.STATE,
            STR.DISTRICT,
            STR.CITY,
            STR.VILLAGE,
            STR.ZIPCODE,
            STR.ADDRESS_TYPE
        FROM ECOMMERCE.CLEAN.CLEAN_USER_STREAM AS STR
        INNER JOIN ECOMMERCE.USER_MART.DIM_USER AS DU
            ON STR.USER_ID = DU.USER_ID
    ) AS SRC
        ON ADDR.ADDRESS_ID = SRC.ADDRESS_ID

    WHEN MATCHED THEN
        UPDATE SET
            ADDR.USER_KEY     = SRC.USER_KEY,
            ADDR.COUNTRY      = SRC.COUNTRY,
            ADDR.STATE        = SRC.STATE,
            ADDR.DISTRICT     = SRC.DISTRICT,
            ADDR.CITY         = SRC.CITY,
            ADDR.VILLAGE      = SRC.VILLAGE,
            ADDR.ZIPCODE      = SRC.ZIPCODE,
            ADDR.ADDRESS_TYPE = SRC.ADDRESS_TYPE

    WHEN NOT MATCHED THEN
        INSERT (ADDRESS_ID, USER_KEY, COUNTRY, STATE, DISTRICT, CITY, VILLAGE, ZIPCODE, ADDRESS_TYPE)
        VALUES (SRC.ADDRESS_ID, SRC.USER_KEY, SRC.COUNTRY, SRC.STATE, SRC.DISTRICT, SRC.CITY, SRC.VILLAGE, SRC.ZIPCODE, SRC.ADDRESS_TYPE);

    RETURN 'DIM_ADDRESS LOAD SUCCESSFUL';
END;
$$;


